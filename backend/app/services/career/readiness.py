"""Readiness inference: versioned model -> calibrated estimate, band, SHAP explanation,
out-of-distribution warnings and a deterministic plain-language summary.

Nothing here is generated by the LLM. If no validated model is loaded, callers receive an
explicit 'unavailable' result — never a fabricated score.
"""

from __future__ import annotations

import math
import uuid
from typing import Any

import numpy as np
import pandas as pd
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.ml.explain import explain_single, make_explainer
from app.ml.feature_schema import FEATURE_BY_NAME, FEATURE_NAMES, TARGET_DEFINITION
from app.ml.registry import LoadedModel, registry
from app.models import Prediction, TwinSnapshot
from app.services.twin.features import known_share

BAND_LABELS = {
    "not_yet_ready": "Not yet interview-ready",
    "developing": "Developing",
    "interview_ready": "Likely interview-ready",
}

LOW_INFORMATION_SHARE = 0.5


def _explainer(model: LoadedModel) -> Any:
    with model._lock:
        if model._explainer is None:
            model._explainer = make_explainer(model.pipeline[-1], model.background)
        return model._explainer


def _band(model: LoadedModel, p: float) -> str:
    for b in model.manifest["thresholds"]["bands"]:
        if b["low"] <= p < b["high"] or (p >= b["high"] and b["high"] >= 1.0):
            return b["name"]
    return model.manifest["thresholds"]["bands"][-1]["name"]


def _ood_warnings(model: LoadedModel, features: dict[str, float | None]) -> list[dict[str, Any]]:
    warnings = []
    ranges = model.manifest.get("training_ranges", {})
    for name, value in features.items():
        r = ranges.get(name)
        if value is None or r is None:
            continue
        if value < r["p01"] or value > r["p99"]:
            warnings.append(
                {
                    "code": "out_of_distribution",
                    "feature": name,
                    "message": (
                        f"{FEATURE_BY_NAME[name].label} ({value:.3g}) is outside the range seen in 98% of "
                        f"training records ({r['p01']:.2f}–{r['p99']:.2f}); the estimate is less reliable."
                    ),
                }
            )
    return warnings


def predict(features: dict[str, float | None], model: LoadedModel | None = None) -> dict[str, Any]:
    model = model or registry.active()
    if model is None:
        return {"available": False, **registry.status()}
    X = pd.DataFrame(
        [[np.nan if features[f] is None else features[f] for f in FEATURE_NAMES]], columns=list(FEATURE_NAMES), dtype=float
    )
    raw = float(model.pipeline.predict_proba(X)[0, 1])
    calibrated = float(model.calibrated.predict_proba(X)[0, 1]) if model.calibrated is not None else None
    validated = model.calibration_validated and calibrated is not None
    score_for_band = calibrated if calibrated is not None else raw
    band = _band(model, score_for_band)
    explanation = explain_single(model.pipeline, _explainer(model), features)

    warnings: list[dict[str, Any]] = []
    if model.is_synthetic:
        warnings.append(
            {
                "code": "synthetic_model",
                "message": (
                    "This model was trained on SYNTHETIC development data. Treat the estimate as a demonstration "
                    "of the method, not as evidence about you."
                ),
            }
        )
    if not validated:
        warnings.append(
            {
                "code": "uncalibrated",
                "message": ("Calibration is not validated for this model, so no probability is shown — only a band."),
            }
        )
    share = known_share(features)
    if share < LOW_INFORMATION_SHARE:
        warnings.append(
            {
                "code": "low_information",
                "message": (
                    f"Only {share:.0%} of the model's inputs are known for your profile; many are treated as unknown, "
                    "so the estimate is uncertain. Completing your profile and assessments will help."
                ),
            }
        )
    warnings += _ood_warnings(model, features)

    display = None
    if validated:
        display = {
            "value": round((calibrated or 0.0) * 20) / 20,
            "rounding": "nearest 5%",
            "test_ece": model.manifest["calibration"]["test_ece_calibrated"],
        }
    return {
        "available": True,
        "model_version": model.version,
        "model_db_id": model.db_id,
        "is_synthetic_model": model.is_synthetic,
        "target_definition": TARGET_DEFINITION,
        "band": band,
        "band_label": BAND_LABELS.get(band, band),
        "probability": display,
        "raw_score": raw,
        "calibrated_score": calibrated,
        "calibration_validated": validated,
        "known_input_share": round(share, 3),
        "explanation": explanation,
        "summary": summarise(explanation),
        "warnings": warnings,
        "limitations": model.manifest.get("limitations", []),
    }


def summarise(explanation: dict[str, Any], k: int = 3) -> str:
    """Deterministic sentence built only from the computed attributions."""
    contribs = [c for c in explanation["contributions"] if abs(c["contribution"]) > 1e-4]
    ups = [c for c in contribs if c["contribution"] > 0][:k]
    downs = [c for c in contribs if c["contribution"] < 0][:k]

    def phrase(c: dict[str, Any]) -> str:
        return f"{c['label']} ({c['display_value']})"

    parts = []
    if ups:
        parts.append("Factors that raised the model's estimate: " + ", ".join(phrase(c) for c in ups) + ".")
    if downs:
        parts.append("Factors that lowered it: " + ", ".join(phrase(c) for c in downs) + ".")
    parts.append(
        "These are model attributions (associations in the training data), not proof that changing a "
        "factor would change real-world outcomes."
    )
    return " ".join(parts)


def store_prediction(db: Session, user_id: uuid.UUID, snapshot: TwinSnapshot, result: dict[str, Any]) -> Prediction:
    pred = Prediction(
        user_id=user_id,
        model_version_id=result["model_db_id"],
        snapshot_id=snapshot.id,
        raw_score=result["raw_score"],
        probability=result["probability"]["value"] if result["probability"] else None,
        band=result["band"],
        explanation={
            "output_space": result["explanation"]["output_space"],
            "base_value": result["explanation"]["base_value"],
            "contributions": result["explanation"]["contributions"],
            "summary": result["summary"],
        },
        warnings=result["warnings"],
        features=snapshot.features,
    )
    db.add(pred)
    db.flush()
    return pred


def prediction_history(db: Session, user_id: uuid.UUID, limit: int = 50) -> list[Prediction]:
    return list(
        db.scalars(select(Prediction).where(Prediction.user_id == user_id).order_by(Prediction.created_at.desc()).limit(limit))
    )


def finite(v: float | None) -> float | None:
    return None if v is None or (isinstance(v, float) and math.isnan(v)) else v
